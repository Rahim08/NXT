"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { useI18n } from "@/lib/i18n/provider";

const navItems = [
  { key: "home" as const, path: "/", icon: HomeIcon },
  { key: "today" as const, path: "/today", icon: TodayIcon },
  { key: "inbox" as const, path: "/inbox", icon: InboxIcon },
  { key: "projects" as const, path: "/projects", icon: ProjectsIcon },
  { key: "import" as const, path: "/import", icon: ImportIcon },
  { key: "search" as const, path: "/search", icon: SearchIcon },
];

export function Sidebar() {
  const pathname = usePathname();
  const { t } = useI18n();

  return (
    <aside className="hidden lg:flex flex-col w-[var(--sidebar-width)] h-screen bg-surface border-r border-border fixed left-0 top-0 z-30">
      {/* Logo */}
      <div className="flex items-center gap-3 px-5 py-5 border-b border-border">
        <img
          src="/icon-192x192.png"
          alt="NEXT"
          className="w-8 h-8 rounded-lg"
        />
        <span className="text-lg font-semibold text-text-primary tracking-tight">
          {t.app.name}
        </span>
      </div>

      {/* Navigation */}
      <nav className="flex-1 px-3 py-4 space-y-1">
        {navItems.map((item) => {
          const isActive =
            item.path === "/"
              ? pathname === "/"
              : pathname.startsWith(item.path);
          const Icon = item.icon;
          return (
            <Link
              key={item.path}
              href={item.path}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-[var(--radius-md)] text-sm font-medium transition-colors ${
                isActive
                  ? "bg-accent-light text-accent"
                  : "text-text-secondary hover:bg-surface-hover hover:text-text-primary"
              }`}
            >
              <Icon className="w-5 h-5 flex-shrink-0" />
              <span>{t.nav[item.key]}</span>
            </Link>
          );
        })}
      </nav>

      {/* Settings */}
      <div className="px-3 py-4 border-t border-border">
        <Link
          href="/settings"
          className={`flex items-center gap-3 px-3 py-2.5 rounded-[var(--radius-md)] text-sm font-medium transition-colors ${
            pathname === "/settings"
              ? "bg-accent-light text-accent"
              : "text-text-secondary hover:bg-surface-hover hover:text-text-primary"
          }`}
        >
          <SettingsIcon className="w-5 h-5 flex-shrink-0" />
          <span>{t.nav.settings}</span>
        </Link>
      </div>
    </aside>
  );
}

